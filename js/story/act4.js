  const friend = (id) => St.friend(id);
  const foe = (id) => St.foe(id);
  const E1 = () => VN.S.flags.act1Ending;
  const E3 = () => VN.S.flags.act3Ending || 'a3_late';
  const bg = () => VN.S.background;
